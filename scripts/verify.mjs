// `npm run verify`: build, run every headless scenario spec of every phase, write evidence to
// docs/proof/phase-N/ (report.md + exact inputs + raw outputs). Exit 1 if any check fails.
// The report is deterministic (no timestamps/machine info) so CI can diff it against git.
import { writeFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { listPhases, loadSpecs, runSpec } from './scenario-lib.mjs';

let failed = 0;
for (const phase of listPhases()) {
  const outDir = join('docs', 'proof', phase);
  rmSync(join(outDir, 'runs'), { recursive: true, force: true });
  rmSync(join(outDir, 'inputs'), { recursive: true, force: true });
  const results = loadSpecs(join('tests', 'scenarios', phase)).map((s) => runSpec(s, outDir));
  const ok = results.filter((r) => r.pass).length;
  failed += results.length - ok;

  const md = [
    `# Headless evidence: ${phase}`,
    '',
    '> GENERATED by `npm run verify` (scripts/verify.mjs). Do not edit by hand.',
    `> Specs: \`tests/scenarios/${phase}/\`. Inputs: \`inputs/\`. Raw outputs: \`runs/\`.`,
    '',
    `**Result: ${ok}/${results.length} scenarios pass.** Each scenario is run twice; identical output = deterministic.`,
    '',
    '| ID | Requirement | Result | Output sha256 |',
    '|---|---|---|---|',
    ...results.map((r) => `| ${r.id} | ${r.requirement} | ${r.pass ? 'PASS' : '**FAIL**'} | \`${r.sha256}\` |`),
    '',
    '## Details',
    '',
    ...results.flatMap((r) => [
      `### ${r.id}: ${r.pass ? 'PASS' : 'FAIL'}`,
      '',
      r.requirement,
      '',
      '```',
      r.command,
      '```',
      '',
      ...r.checks.map((c) => `- ${c.pass ? '[x]' : '[ ] **FAIL**'} ${c.detail}`),
      '',
    ]),
  ].join('\n');
  writeFileSync(join(outDir, 'report.md'), md);
  console.log(`${phase}: ${ok}/${results.length} pass -> ${outDir}/report.md`);
  for (const r of results.filter((x) => !x.pass)) {
    console.log(`  FAIL ${r.id}`);
    for (const c of r.checks.filter((x) => !x.pass)) console.log(`    - ${c.detail}`);
  }
}
process.exit(failed ? 1 : 0);
